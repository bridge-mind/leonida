"""Semantic interpreter tests for vector conditional move (v_cndmask_b32) with VCC and EXEC masks.

AMD RDNA2 VALU Instruction Set Architecture:
  v_cndmask_b32_e32 dst, src0, src1
    - Implicit condition mask: VCC (vcc_lo in Wave32, vcc in Wave64).
    - For each lane i in the SIMD wave:
        if EXEC[i] == 1:
            dst[i] = src1[i] if (VCC[i] == 1) else src0[i]
        else:
            dst[i] = dst_previous[i]  (inactive lanes preserve background state)

  v_cndmask_b32_e64 dst, src0, src1, cond_mask
    - Explicit condition mask: any SGPR, SGPR pair, or VCC.
    - Operates under EXEC mask identically to the e32 encoding.

Divergence Scenarios:
  1. Uniform Conditions:
     - All lanes condition 0 (VCC == 0): all active lanes select src0.
     - All lanes condition 1 (VCC == ~0): all active lanes select src1.
  2. Alternating / Checkered Divergence:
     - Alternating bit patterns (0x55555555 / 0xAAAAAAAA) across active lanes.
  3. Half-Wave and Strided Divergence:
     - Divergent execution across low-half vs high-half (lanes 0..15 vs 16..31 in Wave32;
       lanes 0..31 vs 32..63 in Wave64).
     - Power-of-two strided clusters (blocks of 2, 4, 8, 16 lanes).
  4. Sparse Single-Bit Divergence:
     - Exact one-hot / one-cold condition masks walking across all lane indices.
  5. Data-Dependent Divergence:
     - Dynamic condition masks generated by vector comparisons (v_cmp_*).
  6. EXEC Mask Inactive Preservation:
     - Lanes masked out by EXEC (EXEC[i] == 0) MUST preserve their previous VGPR values
       without corruption, regardless of src0, src1, or VCC.
     - Zero EXEC (EXEC == 0): whole-wave no-op across all vector registers.
  7. Correlated and Orthogonal Divergence:
     - Structured If-Then-Else: Then block (EXEC = EXEC & VCC) and Else block
       (EXEC = EXEC & ~VCC) executing v_cndmask_b32 independently and re-converging.
     - Orthogonal masks: partial wave execution where EXEC and VCC vary independently.
  8. Wave64 Cross-Half Divergence:
     - Independent condition patterns in low half (lanes 0..31) and high half (lanes 32..63).
     - Half-disabled waves (EXEC low-half only or high-half only).
     - Boundary transitions across the 32-lane boundary (lane 31 vs lane 32).
  9. SPIR-V Translation and Interpretation:
     - Translation through tools/rdna2spirv.py emitting OpSelect with lane %active.
     - Execution via tests/semantic/spirv_mini_interp.py.
  10. Negative Controls and Invariant Mutations:
     - Condition inversion, operand swapping, and single-bit flip sensitivity.

Standard library only: zero game data, no external dependencies, Python 3.9+ compatible.
"""
