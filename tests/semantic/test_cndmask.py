class TestCndmaskNegativeControls(unittest.TestCase):
    """Negative controls and sensitivity verification against corruptions."""

    def test_vcc_inversion_mutation(self) -> None:
        """Inverting VCC must invert selection for every differing lane."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        s0 = [0x100 + i for i in range(32)]
        s1 = [0x200 + i for i in range(32)]
        wave.init_vgpr(0, s0)
        wave.init_vgpr(1, s1)
        wave.set_exec(0xFFFFFFFF)

        vcc = 0x12345678
        wave.set_vcc(vcc)
        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        res_normal = wave.get_vgpr(2)

        wave.set_vcc(~vcc & MASK32)
        wave.execute_v_cndmask_e32(dst_v=3, src0="v0", src1="v1")
        res_inverted = wave.get_vgpr(3)

        self.assertNotEqual(res_normal, res_inverted)
        for i in range(32):
            self.assertNotEqual(res_normal[i], res_inverted[i])

    def test_exec_clearing_prevents_updates(self) -> None:
        """Clearing EXEC mask ensures destination is completely unmodified."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        init_val = [0xFEED0000 + i for i in range(32)]
        wave.init_vgpr(2, init_val)
        wave.init_vgpr(0, 1)
        wave.init_vgpr(1, 2)
        wave.set_vcc(0xFFFFFFFF)
        wave.set_exec(0x00000000)  # corrupt EXEC to 0

        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        self.assertEqual(wave.get_vgpr(2), init_val)

    def test_single_bit_flip_sensitivity(self) -> None:
        """Flipping exactly one bit in VCC alters strictly and only that lane."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        s0 = [10 + i for i in range(32)]
        s1 = [90 + i for i in range(32)]
        wave.init_vgpr(0, s0)
        wave.init_vgpr(1, s1)
        wave.set_exec(0xFFFFFFFF)

        base_vcc = 0x55555555
        wave.set_vcc(base_vcc)
        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        base_res = wave.get_vgpr(2)

        for flip_lane in range(32):
            flipped_vcc = base_vcc ^ (1 << flip_lane)
            wave.set_vcc(flipped_vcc)
            wave.execute_v_cndmask_e32(dst_v=3, src0="v0", src1="v1")
            flipped_res = wave.get_vgpr(3)

            for lane in range(32):
                if lane == flip_lane:
                    self.assertNotEqual(flipped_res[lane], base_res[lane])
                else:
                    self.assertEqual(flipped_res[lane], base_res[lane])


