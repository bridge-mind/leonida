class TestCndmaskReferenceOracle(unittest.TestCase):
    """Verifies core mathematical reference oracle, truth table, and invariants."""

    def test_truth_table_active_lane(self) -> None:
        """For active lanes, cond_bit=0 selects src0, cond_bit=1 selects src1."""
        src0 = 0x11111111
        src1 = 0x22222222
        prev = 0x99999999
        self.assertEqual(ref_cndmask_lane(src0, src1, cond_bit=0, exec_bit=1, prev_dst=prev), src0)
        self.assertEqual(ref_cndmask_lane(src0, src1, cond_bit=1, exec_bit=1, prev_dst=prev), src1)

    def test_inactive_lane_preservation(self) -> None:
        """When exec_bit=0, previous dst is preserved regardless of cond, src0, or src1."""
        src0 = 0xAAAAAAAA
        src1 = 0xBBBBBBBB
        prev = 0xDEADBEEF
        self.assertEqual(ref_cndmask_lane(src0, src1, cond_bit=0, exec_bit=0, prev_dst=prev), prev)
        self.assertEqual(ref_cndmask_lane(src0, src1, cond_bit=1, exec_bit=0, prev_dst=prev), prev)

    def test_complement_duality(self) -> None:
        """Duality: cndmask(src0, src1, cond) == cndmask(src1, src0, 1 - cond)."""
        rng = random.Random(20261122)
        for _ in range(100):
            s0 = rng.getrandbits(32)
            s1 = rng.getrandbits(32)
            for c in (0, 1):
                res_normal = ref_cndmask_lane(s0, s1, cond_bit=c, exec_bit=1)
                res_dual = ref_cndmask_lane(s1, s0, cond_bit=1 - c, exec_bit=1)
                self.assertEqual(res_normal, res_dual)

    def test_idempotence(self) -> None:
        """Idempotence: cndmask(x, x, cond) == x for any condition when active."""
        rng = random.Random(20261122)
        for _ in range(50):
            x = rng.getrandbits(32)
            self.assertEqual(ref_cndmask_lane(x, x, cond_bit=0, exec_bit=1), x)
            self.assertEqual(ref_cndmask_lane(x, x, cond_bit=1, exec_bit=1), x)

    def test_extreme_32bit_values(self) -> None:
        """Bit patterns including 0, max uint, signed limits, and float bit patterns."""
        extremes = [
            0x00000000, 0xFFFFFFFF, 0x7FFFFFFF, 0x80000000,
            0x3F800000, 0xBF800000, 0x7F800000, 0xFF800000,
        ]
        for s0 in extremes:
            for s1 in extremes:
                self.assertEqual(ref_cndmask_lane(s0, s1, 0, 1), s0)
                self.assertEqual(ref_cndmask_lane(s0, s1, 1, 1), s1)


class TestCndmaskWave32Divergence(unittest.TestCase):
    """Verifies SIMD Wave32 execution across divergent lane patterns."""

    def test_uniform_all_false_vcc(self) -> None:
        """All 32 lanes active with VCC = 0x00000000 (all select src0)."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        src0_vals = [0x1000 + i for i in range(32)]
        src1_vals = [0x2000 + i for i in range(32)]
        wave.init_vgpr(0, src0_vals)
        wave.init_vgpr(1, src1_vals)
        wave.set_vcc(0x00000000)
        wave.set_exec(0xFFFFFFFF)
        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        self.assertEqual(wave.get_vgpr(2), src0_vals)

    def test_uniform_all_true_vcc(self) -> None:
        """All 32 lanes active with VCC = 0xFFFFFFFF (all select src1)."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        src0_vals = [0x1000 + i for i in range(32)]
        src1_vals = [0x2000 + i for i in range(32)]
        wave.init_vgpr(0, src0_vals)
        wave.init_vgpr(1, src1_vals)
        wave.set_vcc(0xFFFFFFFF)
        wave.set_exec(0xFFFFFFFF)
        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        self.assertEqual(wave.get_vgpr(2), src1_vals)

    def test_checkered_divergence(self) -> None:
        """Alternating lanes: VCC = 0x55555555 (even lanes select src1, odd lanes select src0)."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        src0_vals = [0xA000 + i for i in range(32)]
        src1_vals = [0xB000 + i for i in range(32)]
        wave.init_vgpr(0, src0_vals)
        wave.init_vgpr(1, src1_vals)
        vcc_mask = 0x55555555
        wave.set_vcc(vcc_mask)
        wave.set_exec(0xFFFFFFFF)
        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        expected = [src1_vals[i] if (i % 2 == 0) else src0_vals[i] for i in range(32)]
        self.assertEqual(wave.get_vgpr(2), expected)

    def test_inverted_checkered_divergence(self) -> None:
        """Alternating lanes: VCC = 0xAAAAAAAA (odd lanes select src1, even lanes select src0)."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        src0_vals = [0xC000 + i for i in range(32)]
        src1_vals = [0xD000 + i for i in range(32)]
        wave.init_vgpr(0, src0_vals)
        wave.init_vgpr(1, src1_vals)
        vcc_mask = 0xAAAAAAAA
        wave.set_vcc(vcc_mask)
        wave.set_exec(0xFFFFFFFF)
        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        expected = [src1_vals[i] if (i % 2 == 1) else src0_vals[i] for i in range(32)]
        self.assertEqual(wave.get_vgpr(2), expected)

    def test_half_wave_divergence(self) -> None:
        """Half-wave divergence: lanes 0..15 select src1, lanes 16..31 select src0."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        src0_vals = [100 + i for i in range(32)]
        src1_vals = [200 + i for i in range(32)]
        wave.init_vgpr(0, src0_vals)
        wave.init_vgpr(1, src1_vals)
        wave.set_vcc(0x0000FFFF)
        wave.set_exec(0xFFFFFFFF)
        wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
        expected = [src1_vals[i] if i < 16 else src0_vals[i] for i in range(32)]
        self.assertEqual(wave.get_vgpr(2), expected)

    def test_power_of_two_strides(self) -> None:
        """Power-of-two stride clusters: blocks of 2, 4, 8, 16 divergent lanes."""
        for stride in (2, 4, 8, 16):
            with self.subTest(stride=stride):
                wave = CndmaskWaveInterpreter(wave_size=32)
                src0_vals = [1000 + i for i in range(32)]
                src1_vals = [2000 + i for i in range(32)]
                wave.init_vgpr(0, src0_vals)
                wave.init_vgpr(1, src1_vals)
                vcc = 0
                for i in range(32):
                    if (i // stride) % 2 == 1:
                        vcc |= (1 << i)
                wave.set_vcc(vcc)
                wave.set_exec(0xFFFFFFFF)
                wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
                expected = [src1_vals[i] if ((i // stride) % 2 == 1) else src0_vals[i] for i in range(32)]
                self.assertEqual(wave.get_vgpr(2), expected)

    def test_sparse_single_bit_walk(self) -> None:
        """Walks each bit 0..31 with only that single lane condition true, then inverted."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        src0 = [0x10 + i for i in range(32)]
        src1 = [0x80 + i for i in range(32)]
        wave.init_vgpr(0, src0)
        wave.init_vgpr(1, src1)
        wave.set_exec(0xFFFFFFFF)

        for bit in range(32):
            wave.set_vcc(1 << bit)
            wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
            expected_one_hot = [src1[i] if i == bit else src0[i] for i in range(32)]
            self.assertEqual(wave.get_vgpr(2), expected_one_hot)

            wave.set_vcc(~(1 << bit) & MASK32)
            wave.execute_v_cndmask_e32(dst_v=2, src0="v0", src1="v1")
            expected_one_cold = [src0[i] if i == bit else src1[i] for i in range(32)]
            self.assertEqual(wave.get_vgpr(2), expected_one_cold)

    def test_data_dependent_divergence_from_cmp(self) -> None:
        """Divergence created dynamically by v_cmp_gt_u32."""
        wave = CndmaskWaveInterpreter(wave_size=32)
        # v0 contains lane IDs: 0, 1, 2, ..., 31
        wave.init_vgpr(0, list(range(32)))
        wave.init_vgpr(1, 111)  # src0
        wave.init_vgpr(2, 222)  # src1
        wave.set_exec(0xFFFFFFFF)

        # Condition: lane_id > 10 (lanes 0..10 false, lanes 11..31 true)
        wave.execute_v_cmp("gt_u32", "v0", 10, dst_mask="vcc")
        self.assertEqual(wave.vcc, 0xFFFFF800)

