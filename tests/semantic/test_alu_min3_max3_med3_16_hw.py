def run_rows(rows):
    """Translate one pixel shader that runs every row and stores v4 at BASE + 4k; return the stored words."""
    body = [f"s_mov_b32 s0, {BASE:#x}", "s_mov_b32 s1, 0", "s_mov_b32 s2, 0x1000", "s_mov_b32 s3, 0x31016fac"]
    for k, (line, a, b, c, _) in enumerate(rows):
        body += [f"v_mov_b32 v1, {a:#x}", f"v_mov_b32 v2, {b:#x}", f"v_mov_b32 v3, {c:#x}", "v_mov_b32 v4, 0xdeadbeef",
                 line, f"buffer_store_dword v4, off, s[0:3], 0 offset:{4 * k}"]
    body += ["exp mrt0 v4, v4, v4, v4 done vm", "s_endpgm"]
    with tempfile.TemporaryDirectory() as tmp:
        os.mkdir(os.path.join(tmp, "disasm"))
        src = os.path.join(tmp, "disasm", "ps_minmax16_hw.s")
        with open(os.path.join(tmp, "ps_minmax16_hw.dxbc"), "wb") as f:
            f.write(STUB_DXBC)
        with open(src, "w", encoding="utf-8") as f:
            f.write("; test_alu_min3_max3_med3_16_hw\n" + "".join(f"\t{x}\n" for x in body))
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", ResourceWarning)
            spv = rdna2spirv.translate(src)
    memory = {}
    si.run_fragment(spv, memory=memory)
    return [memory.get(BASE + 4 * k) for k in range(len(rows))]


class MeasuredWords(unittest.TestCase):
    def test_rows(self):
        groups = {}
        for row in MEASURED:
            groups.setdefault(row[0].split()[0], []).append(row)
        for op, rows in groups.items():
            got = run_rows(rows)
            for row, word in zip(rows, got):
                with self.subTest(insn=row[0], v1=hex(row[1]), v2=hex(row[2]), v3=hex(row[3])):
                    self.assertEqual(word, row[4])

    def test_all_nan_keeps_src0(self):
        """When all three operands are NaN, v_min3_f16/v_max3_f16 return src0's exact 16-bit pattern."""
        rows = ALL_NAN_SRC0_SIGNALLING
        self.assertEqual(run_rows(rows), [row[4] for row in rows])


