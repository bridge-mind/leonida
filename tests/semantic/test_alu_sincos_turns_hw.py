def run_rows(rows):
    lines = [f"s_mov_b32 s0, {OUT:#x}", "s_mov_b32 s1, 0", "s_mov_b32 s2, 0x1000", "s_mov_b32 s3, 0x31016fac"]
    for k, (op, x, _) in enumerate(rows):
        lines += [f"v_mov_b32 v1, {x:#x}", "v_mov_b32 v4, 0xdeadbeef", f"{op} v4, v1",
                  f"buffer_store_dword v4, off, s[0:3], 0 offset:{4 * k}"]
    lines += ["exp mrt0 v4, v4, v4, v4 done vm", "s_endpgm"]
    with tempfile.TemporaryDirectory() as tmp:
        os.mkdir(os.path.join(tmp, "disasm"))
        src = os.path.join(tmp, "disasm", "ps_sincos_turns.s")
        with open(os.path.join(tmp, "ps_sincos_turns.dxbc"), "wb") as f:
            f.write(STUB_DXBC)
        with open(src, "w", encoding="utf-8") as f:
            f.write("; test_alu_sincos_turns_hw\n" + "".join(f"\t{x}\n" for x in lines))
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", ResourceWarning)
            spv = rdna2spirv.translate(src)
    memory = {}
    si.run_fragment(spv, memory=memory)
    return [memory.get(OUT + 4 * k) for k in range(len(rows))]


def is_nan(op, word):
    if op.endswith("f16"):
        return (word & 0x7C00) == 0x7C00 and word & 0x3FF
    return (word & 0x7F800000) == 0x7F800000 and word & 0x7FFFFF


class MeasuredTurns(unittest.TestCase):
    def test_rows(self):
        for row, word in zip(MEASURED, run_rows(MEASURED)):
            op, x, want = row
            with self.subTest(insn=op, v1=hex(x)):
                if is_nan(op, want):
                    # the hardware's NaN for sin/cos(+-inf) and of a NaN operand: only NaN-ness is pinned (payloads
                    # are the driver's in a translation)
                    self.assertTrue(is_nan(op, word), hex(word))
                    self.assertEqual(word >> 16 if op.endswith("f16") else 0, want >> 16 if op.endswith("f16") else 0)
                else:
                    self.assertEqual(word, want)


