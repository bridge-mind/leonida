def rounding_shader(o, d, inv, ext):
    words = [f2u(ext), *[f2u(c) for c in o], *[f2u(c) for c in d], *[f2u(c) for c in inv]]
    lines = ["v_mov_b32_e32 v1, 0x5", "v_mov_b32_e32 v2, 0"]
    lines += [f"v_mov_b32_e32 v{3 + i}, 0x{w:x}" for i, w in enumerate(words)]
    lines += ["s_mov_b32 s4, 0x10", "s_mov_b32 s5, 0x80000000", "s_mov_b32 s6, -1", "s_mov_b32 s7, 0x81000000",
              "image_bvh64_intersect_ray v[20:23], [v1, v2, v3, v4, v5, v6, v7, v8, v9, v10, v11, v12], s[4:7]",
              "exp mrt0 v20, v21, v22, v23 done vm", "s_endpgm"]
    return translate_lines("ps_bvh_box_hw_rounding", lines)


class MeasuredRounding(unittest.TestCase):
    def test_slab_distances_round_toward_zero(self):
        for label, o, d, inv, ext, lo, hi, hit in ROUNDING:
            with self.subTest(label):
                mem = node("box32", [0x40, 0x48, 0x50, 0x58], [(*lo, *hi), FAR, FAR, FAR])
                got = list(mrt0_words(rounding_shader(o, d, inv, ext), memory=mem))
                self.assertEqual(got, [0x40 if hit else MISS, MISS, MISS, MISS])

